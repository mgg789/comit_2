"""Regenerate the gateway contract from the actual agents FastAPI application."""

import json
from pathlib import Path

from agents_service.main import create_app


def type_name(value: str) -> str:
    """Namespace generated DTOs so existing shared contracts keep their names."""
    return "Agents" + value.replace("-", "_")


def ts_type(schema: dict | bool) -> str:
    """Convert the subset emitted by these Pydantic models to lossless TS DTO types."""
    if isinstance(schema, bool):
        return "unknown" if schema else "never"
    if "$ref" in schema:
        return type_name(schema["$ref"].rsplit("/", 1)[-1])
    if "enum" in schema:
        return " | ".join(json.dumps(value, ensure_ascii=False) for value in schema["enum"])
    if "const" in schema:
        return json.dumps(schema["const"], ensure_ascii=False)
    for key in ("anyOf", "oneOf", "allOf"):
        if key in schema:
            separator = " & " if key == "allOf" else " | "
            return "(" + separator.join(ts_type(child) for child in schema[key]) + ")"
    kind = schema.get("type")
    if kind == "integer" and schema.get("minimum") == 0 and schema.get("maximum") == 7:
        return "0 | 1 | 2 | 3 | 4 | 5 | 6 | 7"
    if kind == "array":
        return "Array<" + ts_type(schema.get("items", {})) + ">"
    if kind == "object":
        properties = schema.get("properties", {})
        required = schema.get("required", [])
        if properties:
            return "{ " + " ".join(json.dumps(key) + ("" if key in required else "?") + ": " + ts_type(value) + ";"
                                    for key, value in properties.items()) + " }"
        patterns = list(schema.get("patternProperties", {}).values())
        if patterns:
            return "Record<string, " + " | ".join(dict.fromkeys(ts_type(value) for value in patterns)) + ">"
        return "Record<string, " + ts_type(schema.get("additionalProperties", True)) + ">"
    return {"string": "string", "integer": "number", "number": "number", "boolean": "boolean", "null": "null"}.get(kind, "unknown")


if __name__ == "__main__":
    root = Path(__file__).resolve().parents[1]
    target = root / "apps/api/src/contracts/agents.openapi.json"
    target.parent.mkdir(parents=True, exist_ok=True)
    spec = create_app().openapi()
    target.write_text(json.dumps(spec, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    lines = ["/** Generated by tests/generate_agents_contract.py; edit Pydantic contracts instead. */"]
    for name, value in sorted(spec["components"]["schemas"].items()):
        description = value.get("description", name).replace("*/", "* /").replace("\n", " ")
        lines.extend([f"/** {description} */", f"export type {type_name(name)} = {ts_type(value)};", ""])
    (root / "packages/shared/src/agents.ts").write_text("\n".join(lines), encoding="utf-8")
